// Offline: update display points without rebuilding terrain or fetching any data.
import { writeFile } from 'node:fs/promises';
import { geoAlbersUsa } from 'd3-geo';
import { mapPlaces } from '../src/data/mapPlaces.js';

const project = geoAlbersUsa().scale(1300).translate([487.5, 305]);
const points = Object.fromEntries(mapPlaces.map(place => {
  const point = project(place.coordinates);
  if (!point?.every(Number.isFinite)) throw new Error('Place outside the map projection: ' + place.id);
  return [place.id, point.map(value => Number(value.toFixed(4)))];
}));
await writeFile(new URL('../src/data/mapPlacePoints.js', import.meta.url),
  '// Generated by npm run prepare:markers; uses the same projection as the terrain.\nexport const mapPlacePoints = ' + JSON.stringify(points, null, 2) + ';\n');
console.log(`Prepared ${mapPlaces.length} geographic display points.`);
